def _render(path: Path, doc_type: str, pages: list[list[tuple]], producer: str, mod_date: str) -> None:
    label, color = HEADINGS[doc_type]
    buf = io.BytesIO()
    c = canvas.Canvas(buf, pagesize=A4, pageCompression=1, invariant=1)  # deterministic bytes
    c.setTitle(f"DocuTrust demo — {label}")
    c.setAuthor("DocuTrust synthetic generator")
    c.setSubject("Synthetic demo document. Not a real filing.")

    for i, lines in enumerate(pages, 1):
        # header band (top of page; reportlab origin is bottom-left)
        c.setFillColor(Color(*color))
        c.rect(0, H - 66, W, 66, fill=1, stroke=0)
        c.setFillColor(Color(1, 1, 1))
        c.setFont(FONT_BOLD, 17)
        c.drawString(42, H - 36, label)
        c.setFont(FONT, 9)
        c.drawString(42, H - 54, "SYNTHETIC DEMO DOCUMENT - NOT A REAL FILING")

        # border
        c.setStrokeColor(Color(0.8, 0.8, 0.8))
        c.setLineWidth(0.75)
        c.rect(8, 8, W - 16, H - 94, fill=0, stroke=1)

        # watermark
        c.saveState()
        c.translate(W / 2, H / 2 - 120)
        c.rotate(-30)
        c.setFillColor(Color(0.93, 0.87, 0.87))
        c.setFont(FONT_BOLD, 50)
        c.drawCentredString(0, 0, "SYNTHETIC DATA")
        c.restoreState()

        # content
        y = H - 100
        c.setFillColor(Color(0.12, 0.18, 0.25))
        for entry in lines:
            kind = entry[0]
            if kind == "gap":
                y -= LINE_PITCH * entry[1]
                continue
            opt = entry[2] if len(entry) > 2 else {}
            if kind == "text":
                text = entry[1]
                size = opt.get("size", 11)
                bold = opt.get("bold", False)
                col = opt.get("color")
                if col:
                    c.setFillColor(Color(*col))
                else:
                    c.setFillColor(Color(0.12, 0.18, 0.25))
                c.setFont(FONT_BOLD if bold else FONT, size)
                c.drawString(MARGIN_X, y, text)
            elif kind == "kv":
                key, value = entry[1], entry[2]
                c.setFillColor(Color(0.10, 0.36, 0.49))
                c.setFont(FONT_BOLD, 10.5)
                key_label = f"{key}:"
                c.drawString(MARGIN_X, y, key_label)
                kw = c.stringWidth(key_label, FONT_BOLD, 10.5)
                c.setFillColor(Color(0.12, 0.18, 0.25))
                c.setFont(FONT, 10.5)
                c.drawString(MARGIN_X + kw + 8, y, str(value))
            y -= LINE_PITCH

        # footer
        c.setFillColor(Color(0.55, 0.60, 0.65))
        c.setFont(FONT, 10)
        c.drawCentredString(W / 2, 30, f"Page {i} of {len(pages)}")
        c.showPage()

    c.save()

    # Post-process metadata so the CLEAN file is a single-xref, whitelisted
    # producer file and the FORGED file carries its forged bytes.
    doc = fitz.open(stream=buf.getvalue(), filetype="pdf")
    try:
        doc.set_metadata(
            {
                "producer": producer,
                "creator": producer,
                "modDate": mod_date,
                "creationDate": _cdate(YEAR, 10, 1, 9),
                "title": f"DocuTrust demo — {label}",
                "author": "DocuTrust synthetic generator",
            }
        )
        data = stable_id(doc.write())  # full rewrite → exactly one xref section / one %%EOF
    finally:
        doc.close()

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)


def _forge_byte_layout(src: Path, dst: Path) -> None:
    """Turn a clean land deed into the forged variant's byte layout:
    forged producer + mod-date, then a REAL incremental save so the file
    genuinely contains more than one xref section (%%EOF markers)."""
    doc = fitz.open(str(src))
    try:
        doc.set_metadata(
            {
                "producer": FORGED_PRODUCER,
                "creator": FORGED_PRODUCER,
                "modDate": "D:20240315143200",  # 116 days AFTER the deed's 20-11-2023 registration
                "creationDate": _cdate(2023, 11, 18, 14),
            }
        )
        doc.save(str(dst), encryption=fitz.PDF_ENCRYPT_KEEP)
    finally:
        doc.close()

    # append a genuine incremental update (second xref section)
    doc = fitz.open(str(dst))
    try:
        doc.set_metadata({"producer": FORGED_PRODUCER, "creator": FORGED_PRODUCER})
        doc.save(str(dst), incremental=True, encryption=fitz.PDF_ENCRYPT_KEEP)
    finally:
        doc.close()

    # stamp a deterministic /ID over the final bytes (in place, same length)
    dst.write_bytes(stable_id(dst.read_bytes()))


# --------------------------------------------------------------------------
# Build
# --------------------------------------------------------------------------

def build(force: bool = False) -> dict:
    """Generate the clean + forged demo set and a labeled manifest.

    Content-addressed: each document is regenerated only when the rendered
    content (the reportlab pass) differs from what produced the file on disk,
    tracked in .build_state.json. `force=True` regenerates everything. This
    matters because the forged part1/faculty files differ from clean ONLY in
    text values — an exists()-only check would silently keep stale versions
    across generator changes (this exact bug shipped once already)."""
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    state_path = OUT_DIR / ".build_state.json"
    state: dict = json.loads(state_path.read_text()) if state_path.exists() else {}
    manifest: dict = {"generated_at": datetime.now(timezone.utc).isoformat(), "variants": {}}

    builders = {
        "part1": _pages_part1,
        "land": _pages_land,
        "faculty": _pages_faculty,
    }

    for variant, values in (("clean", clean_values()), ("forged", forged_values())):
        set_dir = OUT_DIR / variant
        docs: dict[str, dict] = {}
        mod_date = _cdate(YEAR, 10, 1, 9)  # fixed stamp keeps renders reproducible
        for doc_type, builder in builders.items():
            pages = builder(values)
            path = set_dir / f"{doc_type}.pdf"

            src_tmp = path.with_suffix(".tmp.pdf")
            _render(src_tmp, doc_type, pages, CLEAN_PRODUCER, mod_date)
            src_hash = sha256_of(src_tmp)

            state_key = f"{variant}/{doc_type}"
            up_to_date = not force and path.exists() and state.get(state_key) == src_hash
            if not up_to_date:
                if variant == "forged" and doc_type == "land":
                    # byte-level forgery: forged producer/mod-date + a real
                    # incremental xref section appended to the file
                    _forge_byte_layout(src_tmp, path)
                else:
                    # clean docs and the forged part1/faculty (value forgeries,
                    # whitelisted producer) are the rendered bytes as-is
                    path.write_bytes(src_tmp.read_bytes())
                state[state_key] = src_hash
            src_tmp.unlink(missing_ok=True)

            docs[doc_type] = {
                "filename": path.name,
                "path": str(path.relative_to(REPO_ROOT)),
                "bytes": path.stat().st_size,
                "sha256": sha256_of(path),
            }
        manifest["variants"][variant] = {
            "docs": docs,
            "mutations": MUTATIONS if variant == "forged" else [],
        }

    manifest_path = OUT_DIR / "manifest.json"
    manifest_path.write_text(json.dumps(manifest, indent=2))
    state_path.write_text(json.dumps(state, indent=2))
    return manifest


def sha256_of(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


# PyMuPDF randomizes the second trailer /ID element on every save, which makes
# regenerated files non-byte-identical and would churn the analysis cache keys
# on every rebuild. Normalize: blank all IDs, hash the blanked bytes, stamp
# the digest. Length-preserving, so xref offsets in incremental files survive.
_ID_PATTERN = re.compile(rb"/ID\s*\[<[0-9A-Fa-f]+><[0-9A-Fa-f]+>\]")
_ID_PLACEHOLDER = b"/ID[<00000000000000000000000000000000><00000000000000000000000000000000>]"


def stable_id(data: bytes) -> bytes:
    blanked = _ID_PATTERN.sub(_ID_PLACEHOLDER, data)
    digest = hashlib.sha256(blanked).hexdigest()[:32].upper().encode()
    return blanked.replace(
        _ID_PLACEHOLDER, b"/ID[<" + digest + b"><" + digest + b">]"
    )


if __name__ == "__main__":
    build(force=True)
    m = build()
    sizes = {v: {dt: d["bytes"] for dt, d in info["docs"].items()} for v, info in m["variants"].items()}
